//! C11 emitter for validated IR.
//!
//! Each IR statement becomes one C statement, so C never decides evaluation
//! order. Arithmetic goes through checked helpers built on GCC and Clang
//! overflow builtins. Program text only ever appears inside escaped string
//! literals and is never used as a format string.

use std::fmt::Write;

use crate::ir::{
    BinOp, Callee, Function, MAX_CALL_DEPTH, Operand, PANIC_CALL_DEPTH, PANIC_DIVIDE_BY_ZERO,
    PANIC_OVERFLOW, Program, Rvalue, Stmt, Ty,
};

/// Generates a complete C translation unit. `source_path` appears in panic
/// locations.
pub fn emit(program: &Program, source_path: &str) -> String {
    let mut c = String::new();
    c.push_str(&runtime(source_path));
    if !program.strings.is_empty() {
        c.push_str("\nstatic const chasm_str chasm_strings[] = {\n");
        for text in &program.strings {
            let _ = writeln!(
                c,
                "    {{ {}, {} }},",
                string_literal(text.as_bytes()),
                text.len()
            );
        }
        c.push_str("};\n");
    }
    c.push('\n');
    for function in &program.functions {
        let _ = writeln!(c, "{};", signature(function));
    }
    for function in &program.functions {
        c.push('\n');
        emit_function(&mut c, program, function);
    }
    let main = program.main.expect("the CLI compiles programs with `main`");
    let main = &program.functions[main].name;
    let _ = write!(
        c,
        "\nint main(void) {{\n    chasm_fn_{main}();\n    return 0;\n}}\n"
    );
    c
}

fn runtime(source_path: &str) -> String {
    let path = string_literal(source_path.as_bytes());
    let overflow = string_literal(PANIC_OVERFLOW.as_bytes());
    let divide_by_zero = string_literal(PANIC_DIVIDE_BY_ZERO.as_bytes());
    let call_depth = string_literal(PANIC_CALL_DEPTH.as_bytes());
    format!(
        r#"/* Generated by chasm {version}. */
#include <inttypes.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

typedef struct {{ const char *ptr; size_t len; }} chasm_str;

static const char chasm_source_path[] = {path};
static uint32_t chasm_depth = 1;

static _Noreturn void chasm_panic(const char *message, int line, int col) {{
    fflush(stdout);
    fprintf(stderr, "panic: %s\n  at %s:%d:%d\n", message, chasm_source_path, line, col);
    exit(101);
}}

static inline int32_t chasm_add(int32_t a, int32_t b, int line, int col) {{
    int32_t r;
    if (__builtin_add_overflow(a, b, &r)) chasm_panic({overflow}, line, col);
    return r;
}}

static inline int32_t chasm_sub(int32_t a, int32_t b, int line, int col) {{
    int32_t r;
    if (__builtin_sub_overflow(a, b, &r)) chasm_panic({overflow}, line, col);
    return r;
}}

static inline int32_t chasm_mul(int32_t a, int32_t b, int line, int col) {{
    int32_t r;
    if (__builtin_mul_overflow(a, b, &r)) chasm_panic({overflow}, line, col);
    return r;
}}

static inline int32_t chasm_div(int32_t a, int32_t b, int line, int col) {{
    if (b == 0) chasm_panic({divide_by_zero}, line, col);
    if (a == INT32_MIN && b == -1) chasm_panic({overflow}, line, col);
    return a / b;
}}

/* INT32_MIN % -1 is undefined in C but mathematically 0. */
static inline int32_t chasm_rem(int32_t a, int32_t b, int line, int col) {{
    if (b == 0) chasm_panic({divide_by_zero}, line, col);
    if (b == -1) return 0;
    return a % b;
}}

static inline int32_t chasm_neg(int32_t a, int line, int col) {{
    if (a == INT32_MIN) chasm_panic({overflow}, line, col);
    return -a;
}}

static inline void chasm_enter(int line, int col) {{
    if (chasm_depth >= {MAX_CALL_DEPTH}u) chasm_panic({call_depth}, line, col);
    chasm_depth++;
}}

static inline void chasm_print_int(int32_t value) {{
    printf("%" PRId32 "\n", value);
}}

static inline void chasm_print_bool(bool value) {{
    fputs(value ? "true\n" : "false\n", stdout);
}}

static inline void chasm_print_str(chasm_str value) {{
    fwrite(value.ptr, 1, value.len, stdout);
    fputc('\n', stdout);
}}
"#,
        version = env!("CARGO_PKG_VERSION"),
    )
}

fn signature(function: &Function) -> String {
    let ret = function.ret.map_or("void", c_type);
    let params: Vec<String> = function.locals[..function.param_count]
        .iter()
        .enumerate()
        .map(|(id, local)| format!("{} l{id}", c_type(local.ty)))
        .collect();
    let params = if params.is_empty() {
        "void".to_string()
    } else {
        params.join(", ")
    };
    format!("static {ret} chasm_fn_{}({params})", function.name)
}

fn emit_function(c: &mut String, program: &Program, function: &Function) {
    let _ = writeln!(c, "{} {{", signature(function));
    for (id, local) in function.locals.iter().enumerate() {
        if id >= function.param_count {
            let zero = match local.ty {
                Ty::Int => "0",
                Ty::Bool => "false",
                Ty::String => "{ NULL, 0 }",
            };
            let _ = writeln!(
                c,
                "    {} l{id} = {zero}; /* {} */",
                c_type(local.ty),
                local.name
            );
        }
        // Keeps -Wunused warnings quiet for variables the program never reads.
        let _ = writeln!(c, "    (void)l{id};");
    }
    let mut emitter = Emitter {
        c,
        program,
        function,
    };
    emitter.block(&function.body, 1);
    emitter.c.push_str("}\n");
}

struct Emitter<'a> {
    c: &'a mut String,
    program: &'a Program,
    function: &'a Function,
}

impl Emitter<'_> {
    fn block(&mut self, stmts: &[Stmt], depth: usize) {
        for stmt in stmts {
            self.stmt(stmt, depth);
        }
    }

    fn line(&mut self, depth: usize, text: &str) {
        for _ in 0..depth {
            self.c.push_str("    ");
        }
        self.c.push_str(text);
        self.c.push('\n');
    }

    fn stmt(&mut self, stmt: &Stmt, depth: usize) {
        match stmt {
            Stmt::Assign {
                dst,
                value: Rvalue::Call { callee, args, span },
            } => {
                let call = self.call(*callee, args);
                self.line(depth, &format!("chasm_enter({}, {});", span.line, span.col));
                self.line(depth, &format!("l{dst} = {call};"));
                self.line(depth, "chasm_depth--;");
            }
            Stmt::Assign { dst, value } => {
                let value = self.rvalue(value);
                self.line(depth, &format!("l{dst} = {value};"));
            }
            Stmt::Call { callee, args, span } => {
                let call = self.call(*callee, args);
                self.line(depth, &format!("chasm_enter({}, {});", span.line, span.col));
                self.line(depth, &format!("{call};"));
                self.line(depth, "chasm_depth--;");
            }
            Stmt::Print(operand) => {
                let helper = match self.function.operand_ty(*operand) {
                    Ty::Int => "chasm_print_int",
                    Ty::Bool => "chasm_print_bool",
                    Ty::String => "chasm_print_str",
                };
                let operand = operand_c(*operand);
                self.line(depth, &format!("{helper}({operand});"));
            }
            Stmt::If {
                cond,
                then_body,
                else_body,
            } => {
                self.line(depth, &format!("if ({}) {{", operand_c(*cond)));
                self.block(then_body, depth + 1);
                if !else_body.is_empty() {
                    self.line(depth, "} else {");
                    self.block(else_body, depth + 1);
                }
                self.line(depth, "}");
            }
            Stmt::Loop(body) => {
                self.line(depth, "for (;;) {");
                self.block(body, depth + 1);
                self.line(depth, "}");
            }
            Stmt::Break => self.line(depth, "break;"),
            Stmt::Return(None) => self.line(depth, "return;"),
            Stmt::Return(Some(value)) => {
                let value = operand_c(*value);
                self.line(depth, &format!("return {value};"));
            }
        }
    }

    fn rvalue(&self, rvalue: &Rvalue) -> String {
        match rvalue {
            Rvalue::Use(operand) => operand_c(*operand),
            Rvalue::Binary { op, lhs, rhs, span } => {
                let (lhs, rhs) = (operand_c(*lhs), operand_c(*rhs));
                let checked =
                    |helper: &str| format!("{helper}({lhs}, {rhs}, {}, {})", span.line, span.col);
                let compare = |symbol: &str| format!("({lhs} {symbol} {rhs})");
                match op {
                    BinOp::Add => checked("chasm_add"),
                    BinOp::Sub => checked("chasm_sub"),
                    BinOp::Mul => checked("chasm_mul"),
                    BinOp::Div => checked("chasm_div"),
                    BinOp::Rem => checked("chasm_rem"),
                    BinOp::Lt => compare("<"),
                    BinOp::Le => compare("<="),
                    BinOp::Gt => compare(">"),
                    BinOp::Ge => compare(">="),
                    BinOp::Eq => compare("=="),
                    BinOp::Ne => compare("!="),
                }
            }
            Rvalue::Neg { operand, span } => {
                format!(
                    "chasm_neg({}, {}, {})",
                    operand_c(*operand),
                    span.line,
                    span.col
                )
            }
            Rvalue::Not(operand) => format!("!{}", operand_c(*operand)),
            Rvalue::Call { callee, args, .. } => self.call(*callee, args),
        }
    }

    fn call(&self, callee: Callee, args: &[Operand]) -> String {
        let Callee::Fn(func) = callee else {
            unreachable!("the CLI registers no host functions")
        };
        let args: Vec<String> = args.iter().map(|arg| operand_c(*arg)).collect();
        let name = &self.program.functions[func].name;
        format!("chasm_fn_{name}({})", args.join(", "))
    }
}

fn operand_c(operand: Operand) -> String {
    match operand {
        Operand::Local(id) => format!("l{id}"),
        Operand::Int(i32::MIN) => "INT32_MIN".into(),
        Operand::Int(n) if n < 0 => format!("({n})"),
        Operand::Int(n) => n.to_string(),
        Operand::Bool(b) => b.to_string(),
        Operand::Str(id) => format!("chasm_strings[{id}]"),
    }
}

fn c_type(ty: Ty) -> &'static str {
    match ty {
        Ty::Int => "int32_t",
        Ty::Bool => "bool",
        Ty::String => "chasm_str",
    }
}

/// A C string literal holding exactly `bytes`. Printable ASCII passes through
/// except `"`, `\`, and `?` (trigraphs); every other byte becomes a
/// three-digit octal escape, which cannot run into the next character.
fn string_literal(bytes: &[u8]) -> String {
    let mut literal = String::from("\"");
    for &byte in bytes {
        match byte {
            0x20..=0x7e if !matches!(byte, b'"' | b'\\' | b'?') => literal.push(char::from(byte)),
            _ => {
                let _ = write!(literal, "\\{byte:03o}");
            }
        }
    }
    literal.push('"');
    literal
}
